export const UI_MESSAGES: Record<Locale, Record<UiKey, string>> = { en, ru }

export type Translate = (key: UiKey, params?: Record<string, string | number>) => string

/** A translator for one language; unknown placeholders are left as they are. */
export function translator(locale: Locale = 'en'): Translate {
  const dict = UI_MESSAGES[locale] ?? en
  return (key, params = {}) => (dict[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m))
}

/** `?lang=ru` or `?lang=en` in the page URL, else `fallback`: for demos that switch language by link. */
export function detectLocale(fallback: Locale = 'en'): Locale {
  if (typeof location !== 'undefined') {
    const q = new URLSearchParams(location.search).get('lang')
    if (q === 'ru' || q === 'en') return q
  }
  return fallback
}
