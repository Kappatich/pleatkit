import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(path.join(process.cwd(), 'apps', 'demo-crm', 'package.json'));
const { chromium } = require('@playwright/test');
import { pathToFileURL } from 'node:url';

const site = process.argv[2];
const out = process.argv[3];
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 860 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.addInitScript(() => { window.__morphkitNoAutoplay = true; });
await page.goto(pathToFileURL(path.join(site, 'index.html')).href, { waitUntil: 'load' });
await page.waitForTimeout(800);
await page.screenshot({ path: path.join(out, 'hero-01-before.png'), clip: { x: 0, y: 0, width: 1280, height: 860 } });
await page.click('.recipe[data-recipe="overdue"]');
await page.waitForTimeout(4200);
await page.click('.recipe[data-recipe="bars"]');
await page.waitForTimeout(4200);
await page.locator('[data-live]').screenshot({ path: path.join(out, 'hero-02-after.png') });
await page.click('[data-undo]');
await page.waitForTimeout(400);
await page.locator('[data-live]').screenshot({ path: path.join(out, 'hero-03-undo.png') });
await page.emulateMedia({ colorScheme: 'dark' });
await page.waitForTimeout(300);
await page.locator('[data-live]').screenshot({ path: path.join(out, 'hero-04-dark.png') });
await browser.close();
console.log('done');
