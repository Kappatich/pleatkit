import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const require = createRequire(path.join(process.cwd(), 'apps', 'demo-crm', 'package.json'));
const { chromium } = require('@playwright/test');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(pathToFileURL(path.resolve('site/styles/index.html')).href, { waitUntil: 'load' });
await page.waitForTimeout(1500);
const wide = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
await page.screenshot({ path: 'docs/screenshots/styles-gallery-1.png', clip: { x: 0, y: 0, width: 1600, height: 1000 } });
await page.evaluate(() => window.scrollTo(0, 3000));
await page.waitForTimeout(400);
await page.screenshot({ path: 'docs/screenshots/styles-gallery-2.png', clip: { x: 0, y: 0, width: 1600, height: 1000 } });
console.log(JSON.stringify({ errors: errors.slice(0, 5), horizontalScroll: wide }));
await browser.close();
